"""Build the list of generic words that are never shown as model highlights.

Run from backend/:  python -m scripts.build_generic_words
Reads data/prepared.csv, writes core/generic_words.txt (committed; it contains
single common words only, no email content).

A word is "generic" if it appears in at least MIN_SHARE of the legitimate
emails AND at least MIN_SHARE of the phishing emails. Such words ("it",
"please", "email", "information") occur everywhere, so highlighting them
tells a reader nothing, even if LIME gives them some weight.

This list only changes which highlights are SHOWN. It never changes the label,
the risk or any number in reports/.
"""

import re

import pandas as pd

from app.config import PREPARED_DATA_PATH
from core.explainer import GENERIC_WORDS_PATH

MIN_SHARE = 0.15
_WORD = re.compile(r"[a-z]{2,}")


def document_share(texts: pd.Series) -> dict[str, float]:
    """For each word, the share of texts that contain it at least once."""
    counts: dict[str, int] = {}
    for text in texts:
        for word in set(_WORD.findall(text.lower())):
            counts[word] = counts.get(word, 0) + 1
    return {word: n / len(texts) for word, n in counts.items()}


def generic_words(df: pd.DataFrame, min_share: float = MIN_SHARE) -> list[str]:
    legit = document_share(df.loc[df["label"] == 0, "text"])
    phishing = document_share(df.loc[df["label"] == 1, "text"])
    return sorted(w for w in legit.keys() & phishing.keys() if legit[w] >= min_share and phishing[w] >= min_share)


def main() -> None:
    df = pd.read_csv(PREPARED_DATA_PATH, usecols=["label", "text"], keep_default_na=False)
    words = generic_words(df)
    GENERIC_WORDS_PATH.write_text(
        "# Generated by `python -m scripts.build_generic_words`. Do not edit by hand.\n"
        f"# Words in >= {MIN_SHARE:.0%} of BOTH legitimate and phishing emails (data/prepared.csv).\n"
        + "\n".join(words)
        + "\n",
        encoding="utf-8",
    )
    print(f"{len(words)} generic words written to {GENERIC_WORDS_PATH}")


if __name__ == "__main__":
    main()
