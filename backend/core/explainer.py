CLASS_NAMES = ["Safe Email", "Phishing Email"]
LIME_SEED = 42

# Generated by scripts/build_generic_words.py: words common in BOTH classes.
GENERIC_WORDS_PATH = Path(__file__).resolve().parent / "generic_words.txt"
# Hand-picked: frequent in phishing, but meaningless to a reader on their own.
# The rules already highlight the meaningful phrases ("account suspended", ...).
