"""Model attribution with LIME (Phase 3, layer B).

LIME explains what influenced the MODEL, which is not always what a human finds
suspicious. To keep only highlights that mean something to a reader:
  1. drop stop words, generic words and very weak features (is_meaningful),
  2. find each word as a whole word in the original text (find_position),
  3. merge features that stand next to each other into one phrase (merge_adjacent).
"""

