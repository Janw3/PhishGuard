FALLBACK_EXPLANATION = "This is an indicator that was flagged as suspicious by the model. Think carefully before responding to this email or clicking any links – verify the sender through official channels first."


def _whole_word(phrase: str) -> re.Pattern:
    return re.compile(r"\b" + re.escape(phrase) + r"\b", re.IGNORECASE)


def get_explanation(feature: str) -> str:
    """Curated explanation for the first keyword found as a whole word ("fee", not "feedback")."""
    for key, explanation in EXPLANATIONS.items():
        if _whole_word(key).search(feature):
            return explanation
    return FALLBACK_EXPLANATION


def find_position(text: str, token: str) -> tuple[int, int]:
    """First occurrence of token as a whole word (so "it" does not match inside "limited")."""
    match = _whole_word(token).search(text)
    return (match.start(), match.end()) if match else (-1, -1)


def merge_adjacent(text: str, reasons: list[dict]) -> list[dict]:
    """Join model features separated only by spaces or punctuation into one phrase.

    "verify" + "identity" next to each other become one highlight
    "verify identity" with the summed impact, which reads better than two.
    """
    merged: list[dict] = []
    for reason in sorted(reasons, key=lambda r: r["start"]):
        previous = merged[-1] if merged else None
        gap = text[previous["end"] : reason["start"]] if previous else None
        if previous and reason["start"] >= previous["end"] and re.fullmatch(r"[\s,.;:'\"-]{0,3}", gap):
            previous["end"] = reason["end"]
            previous["feature"] = text[previous["start"] : previous["end"]]
            previous["impact"] += reason["impact"]
            previous["explanation"] = get_explanation(previous["feature"])
        else:
            merged.append(dict(reason))
    return merged


def explain(
    text: str,
    classifier: Classifier,
    num_features: int,
    num_samples: int | None = None,
) -> list[dict]:
    # Slow models (transformers) declare a smaller sample count; sklearn models use 5000.
    if num_samples is None:
        num_samples = getattr(classifier, "explain_samples", 5000)

    # A fresh explainer with a fixed seed per call makes the result depend only
    # on the input, not on how many emails were explained before.
    explainer = LimeTextExplainer(class_names=CLASS_NAMES, random_state=LIME_SEED)

    # LIME perturbs the ORIGINAL text; the classifier normalizes internally.
    # That keeps the features (and their positions) in the text the UI shows.
    explanation = explainer.explain_instance(
        text,
        classifier.predict_proba,
        num_features=num_features,
        num_samples=num_samples,
        labels=[1],
    )

    # Only features that push towards phishing.
    positive = [(str(f), float(w)) for f, w in explanation.as_list(label=1) if w > 0]
    if not positive:
        return []
    strongest = max(w for _, w in positive)

    reasons = []
    for feature, weight in positive:
        if weight < MIN_RELATIVE_WEIGHT * strongest or not is_meaningful(feature):
            continue
        start, end = find_position(text, feature)
        if start == -1:
            continue
        reasons.append(
            {
                "id": f"reason_{uuid.uuid4().hex[:8]}",
                "feature": text[start:end],  # exactly as shown, e.g. "PayPal" not "paypal"
                "explanation": get_explanation(feature),
                "impact": weight,
                "start": int(start),
                "end": int(end),
                "source": "model",
                "category": "model",
            }
        )

    reasons = merge_adjacent(text, reasons)
    reasons.sort(key=lambda x: abs(x["impact"]), reverse=True)
    return reasons
